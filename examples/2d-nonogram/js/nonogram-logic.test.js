const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const context = {};
vm.runInNewContext(`${fs.readFileSync('examples/2d-nonogram/js/nonogram-logic.js', 'utf8')}\nthis.NonogramLogic = NonogramLogic;`, context);

const game = new context.NonogramLogic();
game.toggleCell(0, 0);
const snapshot = game.snapshot();
const restored = new context.NonogramLogic();
assert.strictEqual(restored.restore(snapshot).success, true);
assert.deepStrictEqual(JSON.parse(JSON.stringify(restored.snapshot())), JSON.parse(JSON.stringify(snapshot)));
const before = JSON.parse(JSON.stringify(restored.snapshot()));
const invalid = restored.restore({ gridSize: 10, grid: [], solution: [] });
assert.strictEqual(invalid.success, false);
assert.strictEqual(invalid.reason, 'invalid_snapshot');
assert.deepStrictEqual(JSON.parse(JSON.stringify(restored.snapshot())), before);
const zeroMatrix = () => Array.from({ length: 10 }, () => Array(10).fill(0));
const mistakes = zeroMatrix();
mistakes[0][0] = mistakes[0][1] = mistakes[0][2] = 1;
assert.strictEqual(restored.restore({ gridSize: 10, grid: mistakes, solution: zeroMatrix() }).success, true);
assert.strictEqual(restored.getGameState().isGameOver, true);
assert.strictEqual(restored.toggleCell(0, 3).success, false);
const malformed = restored.snapshot();
malformed.grid[0][0] = '<script>';
const gameOverBefore = JSON.parse(JSON.stringify(restored.snapshot()));
assert.strictEqual(restored.restore(malformed).success, false);
assert.deepStrictEqual(JSON.parse(JSON.stringify(restored.snapshot())), gameOverBefore);
console.log('nonogram-logic.test.js passed');
